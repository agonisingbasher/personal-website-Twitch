const languageToggle = document.querySelector("[data-lang-toggle]");
const languageMeta = document.querySelector('meta[name="description"]');
const languageStorageKey = "agonisingbasher-twitch-language";

// Sem isto, uma chave ausente em um idioma imprime literalmente "undefined" na pagina.
function resolveKey(content, key) {
  const value = content[key];
  if (value !== undefined) return value;
  console.warn(`[i18n] chave ausente em um idioma: ${key}`);
  return translations["pt-BR"][key] ?? "";
}

function setLanguage(language) {
  const content = translations[language];
  const isFeedbackPage = document.body.classList.contains("feedback-page");
  document.documentElement.lang = language;
  document.title = resolveKey(content, isFeedbackPage ? "feedbackTitle" : "title");
  languageMeta.content = resolveKey(content, isFeedbackPage ? "feedbackMetaDescription" : "metaDescription");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.innerHTML = resolveKey(content, element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", resolveKey(content, element.dataset.i18nAriaLabel));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = resolveKey(content, element.dataset.i18nAlt);
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.content = resolveKey(content, element.dataset.i18nContent);
  });

  document.querySelectorAll("a[data-lang-link]").forEach((link) => {
    const targetUrl = new URL(link.getAttribute("href"), window.location.href);
    targetUrl.searchParams.set("lang", language);
    link.href = targetUrl.href;
  });

  languageToggle.textContent = language === "pt-BR" ? "EN" : "PT";
  languageToggle.setAttribute("aria-label", resolveKey(content, "switchLanguage"));
  languageToggle.title = resolveKey(content, "switchLanguage");

  try {
    localStorage.setItem(languageStorageKey, language);
  } catch (error) {
    if (error.name !== "SecurityError") throw error;
  }

  const pageUrl = new URL(window.location.href);
  pageUrl.searchParams.set("lang", language);
  pageUrl.hash = window.location.hash;
  history.replaceState(null, "", pageUrl);

  document.dispatchEvent(new CustomEvent("site-language-change", { detail: { language } }));
}

const ptKeys = Object.keys(translations["pt-BR"]);
const enKeys = Object.keys(translations.en);
const parityBreak = ptKeys.filter((key) => !enKeys.includes(key)).concat(enKeys.filter((key) => !ptKeys.includes(key)));
if (parityBreak.length) console.warn(`[i18n] paridade PT/EN quebrada: ${parityBreak.join(", ")}`);

languageToggle.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "pt-BR" ? "en" : "pt-BR");
});

const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
let initialLanguage = requestedLanguage === "en" || requestedLanguage === "pt-BR" ? requestedLanguage : null;
if (!initialLanguage) {
  try {
    initialLanguage = localStorage.getItem(languageStorageKey);
  } catch (error) {
    if (error.name !== "SecurityError") throw error;
  }
}
setLanguage(initialLanguage === "en" ? "en" : "pt-BR");
